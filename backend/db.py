
"""
PostgreSQL persistence for Artha user accounts and portfolios.
Uses Neon PostgreSQL when DATABASE_URL is configured.
"""

from __future__ import annotations

import os
from contextlib import contextmanager
from datetime import datetime, timezone
from typing import Iterator

import psycopg
from psycopg.rows import dict_row




SCHEMA = [
    """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        onboarding_completed INTEGER NOT NULL DEFAULT 0,
        investment_goal TEXT,
        monthly_range TEXT,
        risk_profile TEXT,
        experience TEXT,
        initial_preference TEXT,
        country TEXT NOT NULL DEFAULT 'India',
        currency TEXT NOT NULL DEFAULT 'INR',
        pref_price_alerts INTEGER NOT NULL DEFAULT 1,
        pref_daily_digest INTEGER NOT NULL DEFAULT 1,
        pref_monthly_report INTEGER NOT NULL DEFAULT 0,
        pref_product_updates INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS sessions (
        token TEXT PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        created_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS portfolios (
        user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
        mode TEXT NOT NULL,
        virtual_cash DOUBLE PRECISION NOT NULL,
        initial_capital DOUBLE PRECISION NOT NULL,
        created_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS holdings (
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        symbol TEXT NOT NULL,
        quantity DOUBLE PRECISION NOT NULL,
        average_buy_price DOUBLE PRECISION NOT NULL,
        currency TEXT NOT NULL DEFAULT 'INR',
        average_buy_price_inr DOUBLE PRECISION NOT NULL DEFAULT 0,
        updated_at TEXT NOT NULL,
        PRIMARY KEY (user_id, symbol)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS transactions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        symbol TEXT NOT NULL,
        type TEXT NOT NULL CHECK (type IN ('BUY', 'SELL')),
        quantity DOUBLE PRECISION NOT NULL,
        execution_price DOUBLE PRECISION NOT NULL,
        source TEXT NOT NULL DEFAULT 'trade',
        timestamp TEXT NOT NULL,
        currency TEXT NOT NULL DEFAULT 'INR',
        fx_rate DOUBLE PRECISION NOT NULL DEFAULT 1.0,
        amount_inr DOUBLE PRECISION
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_sessions_user
    ON sessions(user_id)
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_transactions_user
    ON transactions(user_id, timestamp)
    """,
]


def utcnow() -> str:
    return datetime.now(timezone.utc).isoformat()



def connect():
    """Open a PostgreSQL connection to Neon."""
    from dotenv import load_dotenv
    from pathlib import Path

    load_dotenv(Path(__file__).resolve().parent / ".env")

    database_url = os.getenv("DATABASE_URL")
    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is missing. Check backend/.env "
            "and your deployment environment."
        )

    return CompatibleConnection(
        psycopg.connect(
            database_url,
            row_factory=dict_row,
            connect_timeout=15,
        )
    )



class CompatibleConnection:
    """
    Keep existing conn.execute(...) calls working.
    Convert SQLite-style ? placeholders to Psycopg %s placeholders.
    """

    def __init__(self, connection):
        self._connection = connection

    def execute(self, query: str, params=None):
        query = query.replace("?", "%s")
        return self._connection.execute(query, params or ())

    def commit(self):
        self._connection.commit()

    def close(self):
        self._connection.close()


@contextmanager
def db() -> Iterator[CompatibleConnection]:
    """Commit on success, roll back on failure, and always close."""
    conn = connect()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn._connection.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    """Create missing tables and add newer columns to older schemas."""
    with db() as conn:
        for statement in SCHEMA:
            conn.execute(statement)

        # Safe, repeatable migrations for older Artha databases.
        conn.execute("""
            ALTER TABLE transactions
            ADD COLUMN IF NOT EXISTS currency TEXT NOT NULL DEFAULT 'INR'
        """)
        conn.execute("""
            ALTER TABLE transactions
            ADD COLUMN IF NOT EXISTS fx_rate DOUBLE PRECISION NOT NULL DEFAULT 1.0
        """)
        conn.execute("""
            ALTER TABLE transactions
            ADD COLUMN IF NOT EXISTS amount_inr DOUBLE PRECISION
        """)
        conn.execute("""
            ALTER TABLE holdings
            ADD COLUMN IF NOT EXISTS currency TEXT NOT NULL DEFAULT 'INR'
        """)
        conn.execute("""
            ALTER TABLE holdings
            ADD COLUMN IF NOT EXISTS average_buy_price_inr
            DOUBLE PRECISION NOT NULL DEFAULT 0
        """)

        # Preserve SQLite's case-insensitive uniqueness for usernames/emails.
        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower
            ON users (LOWER(username))
        """)
        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
            ON users (LOWER(email))
        """)
